const assert = require("node:assert/strict");
const fs = require("node:fs");
const ts = require("../frontend/node_modules/typescript");
const source = fs.readFileSync(require("node:path").join(__dirname, "../frontend/src/articleValues.ts"), "utf8");
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const moduleExports = {};
new Function("exports", output)(moduleExports);
const { articlePayload, articlePrices, validateArticle, newArticle } = moduleExports;

assert.deepEqual(articlePrices("10", "23", "4"), { net: 10, gross: 12.3, cost: 4, margin: 6, marginPct: 60 });
assert.equal(articlePrices("0", "23", "4").marginPct, null);
assert.equal(articlePrices("2", "23", "4").marginPct, -100);
assert.equal(articlePrices("10", "23", null).margin, null);
assert.equal(articlePrices(null, "23", "4").gross, null);
assert.equal(articlePrices("", "23", "4").net, null);
assert.equal(articlePrices("10", null, "4").gross, null);
const valid = { ...newArticle, code: "P001", name: "Artigo", barcodes: ["00123", "REF-A"] };
assert.deepEqual(validateArticle(valid, []), {});
assert.ok(validateArticle({ ...valid, barcodes: ["00123", " 00123 "] }, []).barcodes);
assert.ok(validateArticle(valid, [{ id: "other", code: "p001", name: "Duplicado" }]).code);
assert.ok(validateArticle(valid, [{ id: "other", code: "P002", name: "Duplicado", barcodes: ["00123"] }]).barcodes);
assert.deepEqual(validateArticle(valid, [{ ...valid, id: "same" }], "same"), {});
for (const value of ["", "-1", "NaN", "1000000001"]) assert.ok(validateArticle({ ...valid, sale_net: value }, []).sale_net);
assert.ok(validateArticle({ ...valid, minimum: "5", reorder: "2" }, []).reorder);
assert.ok(validateArticle({ ...valid, lots: false, expiry: true }, []).expiry);
assert.ok(validateArticle({ ...valid, photo: "http://example.com/image.png" }, []).photo);
assert.ok(validateArticle({ ...valid, attachments: [{ name: "Ficha", url: "javascript:alert(1)" }] }, []).attachments);
assert.ok(validateArticle({ ...valid, additional_photos: ["http://example.com/image.png"] }, []).additional_photos);
assert.equal(articlePayload({ ...valid, internal_notes: "Equipa" }).internal_notes, "Equipa");
assert.equal(articlePayload({ ...valid, quantity: "999", origin: "Local", average_cost: "20" }).quantity, undefined);
assert.equal(articlePayload({ ...valid, reference: "REF" }).reference, "REF");
console.log("PASS: gross margin, zero and missing values, VAT, validation, duplicates and canonical payload.");
